import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../config_manager.php',import.meta.url),'utf8');
const start=source.indexOf('        let npcSceneSavedGlobalStyleCheck =');
const end=source.indexOf('        // Load Settings',start);
const elements=Object.fromEntries(['npcSceneRelationshipStyleCheck','npcSceneStyleUseGlobal','npcSceneStyleStatus','isSlut'].map(id=>[id,{id,checked:false,disabled:false,textContent:''}]));
let onChange;
const ctx=vm.createContext({document:{getElementById:id=>elements[id],addEventListener:(_,fn)=>onChange=fn}});
vm.runInContext(source.slice(start,end),ctx);
const run=script=>vm.runInContext(script,ctx);
const check=elements.npcSceneRelationshipStyleCheck;
const inherit=elements.npcSceneStyleUseGlobal;
run('syncNpcStyleGlobalDefault()');
assert.equal(inherit.checked,true); assert.equal(check.checked,true); assert.equal(check.disabled,true);
run('npcSceneSavedGlobalStyleCheck=false; syncNpcStyleGlobalDefault()');
assert.equal(check.checked,false);
inherit.checked=false;onChange({target:inherit});
check.checked=true;onChange({target:check});
assert.equal(run('npcSceneStyleOverride'),true);assert.equal(check.disabled,false);
elements.isSlut.checked=true;onChange({target:elements.isSlut});
assert.equal(check.checked,false);assert.equal(check.disabled,true);assert.equal(inherit.disabled,true);
assert.match(elements.npcSceneStyleStatus.textContent,/Automatically off/);
elements.isSlut.checked=false;onChange({target:elements.isSlut});
assert.equal(check.checked,true);assert.equal(check.disabled,false);
inherit.checked=true;onChange({target:inherit});
assert.equal(run('npcSceneStyleOverride'),null);assert.equal(check.checked,false);
run('npcSceneSavedGlobalStyleCheck=true; syncNpcStyleGlobalDefault()');
assert.equal(check.checked,true);
elements.isSlut.checked=true;run('syncNpcStyleGlobalDefault()');assert.equal(check.checked,false);
console.log('npc_style_ui_test: global inheritance, manual override, role bypass and restoration passed');
